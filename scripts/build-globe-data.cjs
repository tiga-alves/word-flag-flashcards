// Precompute the original decorative land geometry; never run this in the page.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const polygons = JSON.parse(fs.readFileSync(path.join(root, 'assets/globe-land.json'), 'utf8'));
function contains(x, y, polygon) {
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const [xi, yi] = polygon[i], [xj, yj] = polygon[j];
    if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
const values = [];
const rad = Math.PI / 180;
let row = 0;
for (let lat = -56; lat < 83; lat += 1.1) {
  const step = 1.1 / Math.cos(lat * rad);
  for (let lon = -180 + (row % 2) * step / 2; lon < 180; lon += step) {
    if (!polygons.some(polygon => contains(lon, lat, polygon))) continue;
    const phase = (lon * 12.9898 + lat * 78.233) % (Math.PI * 2);
    const c = Math.cos(lat * rad);
    for (const value of [c * Math.sin(lon * rad), -Math.sin(lat * rad), c * Math.cos(lon * rad), Math.cos(phase), Math.sin(phase)]) values.push(Math.round(value * 32767));
  }
  row++;
}
const data = Buffer.alloc(values.length * 2);
values.forEach((value, i) => data.writeInt16LE(value, i * 2));
fs.writeFileSync(path.join(root, 'globe-data.js'), `// Generated by scripts/build-globe-data.cjs. ${values.length / 5} land points.\nglobalThis.FlagGlobeData = '${data.toString('base64')}';\n`);
console.log(`Generated ${values.length / 5} points (${data.length} bytes before base64).`);
